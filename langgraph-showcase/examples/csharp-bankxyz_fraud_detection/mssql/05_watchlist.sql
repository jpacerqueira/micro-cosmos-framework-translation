IF OBJECT_ID('dbo.WATCHLIST', 'U') IS NOT NULL
    DROP TABLE dbo.WATCHLIST;

CREATE TABLE dbo.WATCHLIST (
    WATCHLIST_ID INT           NOT NULL IDENTITY(1,1),
    LIST_TYPE    VARCHAR(10)   NOT NULL
        CONSTRAINT CHK_LIST_TYPE CHECK (LIST_TYPE IN ('OFAC','PEP','INTERNAL')),
    MATCH_NAME   NVARCHAR(100) NULL,
    MATCH_ACCT   CHAR(10)      NULL,
    LIST_STATUS  VARCHAR(10)   NOT NULL CONSTRAINT DF_WL_STATUS DEFAULT 'ACTIVE'
        CONSTRAINT CHK_LIST_STATUS CHECK (LIST_STATUS IN ('ACTIVE','EXPIRED')),
    CONSTRAINT PK_WATCHLIST PRIMARY KEY (WATCHLIST_ID)
);

CREATE INDEX IX_WL_TYPE_NAME ON dbo.WATCHLIST (LIST_TYPE, LIST_STATUS) INCLUDE (MATCH_NAME);
CREATE INDEX IX_WL_ACCT      ON dbo.WATCHLIST (MATCH_ACCT, LIST_TYPE, LIST_STATUS);
