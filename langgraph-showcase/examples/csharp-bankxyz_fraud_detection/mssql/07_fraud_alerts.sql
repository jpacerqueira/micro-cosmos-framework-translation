-- =============================================================================
-- NatWest Fraud Detection - Fraud Alerts Table
-- SQL Server 2008 R2 Compatible DDL
-- =============================================================================

IF OBJECT_ID('dbo.FRAUD_ALERTS', 'U') IS NOT NULL
    DROP TABLE dbo.FRAUD_ALERTS;

CREATE TABLE dbo.FRAUD_ALERTS (
    ALERT_ID         INT           NOT NULL IDENTITY(1,1),
    TXN_ID           CHAR(16)      NOT NULL,
    ACCT_NO          CHAR(10)      NOT NULL,
    FRAUD_SCORE      DECIMAL(7,4)  NOT NULL,
    ALERT_STATUS     VARCHAR(10)   NOT NULL CONSTRAINT DF_ALERT_STATUS DEFAULT 'PENDING'
        CONSTRAINT CHK_ALERT_STATUS CHECK (ALERT_STATUS IN ('PENDING','REVIEWED','CLOSED','ESCALATED')),
    ANALYST_ID       VARCHAR(20)   NULL,
    RESOLUTION_NOTES NVARCHAR(500) NULL,
    ARCHIVED_FLAG    CHAR(1)       NOT NULL CONSTRAINT DF_ALERT_ARCHIVED DEFAULT 'N',
    CREATED_TS       DATETIME      NOT NULL CONSTRAINT DF_ALERT_CREATED DEFAULT GETDATE(),
    UPDATED_TS       DATETIME      NOT NULL CONSTRAINT DF_ALERT_UPDATED DEFAULT GETDATE(),
    CONSTRAINT PK_FRAUD_ALERTS PRIMARY KEY (ALERT_ID),
    CONSTRAINT FK_ALERT_TXN FOREIGN KEY (TXN_ID)
        REFERENCES dbo.TXN_QUEUE (TXN_ID)
);

CREATE INDEX IX_ALERT_ACCT_STATUS ON dbo.FRAUD_ALERTS (ACCT_NO, ALERT_STATUS, CREATED_TS);
CREATE INDEX IX_ALERT_STATUS_TS   ON dbo.FRAUD_ALERTS (ALERT_STATUS, CREATED_TS);
