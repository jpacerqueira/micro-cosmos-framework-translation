-- =============================================================================
-- NatWest Fraud Detection - Merchant Risk Table
-- SQL Server 2008 R2 Compatible DDL
-- =============================================================================

IF OBJECT_ID('dbo.MERCHANT_RISK', 'U') IS NOT NULL
    DROP TABLE dbo.MERCHANT_RISK;

CREATE TABLE dbo.MERCHANT_RISK (
    MERCHANT_CODE  CHAR(8)   NOT NULL,
    BLOCKED_FLAG   CHAR(1)   NOT NULL CONSTRAINT DF_MERCH_BLOCKED DEFAULT 'N',
    RISK_BAND      VARCHAR(4) NOT NULL
        CONSTRAINT CHK_RISK_BAND CHECK (RISK_BAND IN ('HIGH','MED','LOW')),
    EFFECTIVE_FROM DATETIME  NOT NULL CONSTRAINT DF_MERCH_EFF_FROM DEFAULT GETDATE(),
    EFFECTIVE_TO   DATETIME  NULL,
    CONSTRAINT PK_MERCHANT_RISK PRIMARY KEY (MERCHANT_CODE)
);

CREATE INDEX IX_MERCH_RISK_BAND ON dbo.MERCHANT_RISK (RISK_BAND);
CREATE INDEX IX_MERCH_BLOCKED   ON dbo.MERCHANT_RISK (BLOCKED_FLAG);
