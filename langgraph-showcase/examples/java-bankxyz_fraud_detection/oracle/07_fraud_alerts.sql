-- Oracle 10g note:
--   ALERT_ID uses sequence FD_SEQ (not a trigger — JPA @SequenceGenerator
--   fetches the next value directly via SELECT FD_SEQ.NEXTVAL FROM DUAL).
--
-- Dependencies: TXN_QUEUE (FK), sequence FD_SEQ (00_sequences.sql)
-- Run after:    00_sequences.sql, 02_txn_queue.sql
-- ============================================================================

