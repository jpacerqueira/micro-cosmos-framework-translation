-- ----------------------------------------------------------------------------
-- FRAUD_ALERTS
-- Every transaction that scores at or above the fraud threshold (0.75).
--
-- ALERT_STATUS state machine (AlertStatus enum in Java):
--   PENDING    — created by AlertWriterService; awaiting analyst review
--   REVIEWED   — analyst has examined the case
--   CLOSED     — case resolved; no further action
--   ESCALATED  — mandatory escalation (OFAC/PEP hit); requires compliance sign-off
--
-- Valid transitions:
--   PENDING → REVIEWED → CLOSED
--   PENDING → ESCALATED          (OFAC / PEP watchlist hits only)
--
-- FRAUD_SCORE is stored with 4 decimal places (NUMBER(7,4)).
-- ----------------------------------------------------------------------------
CREATE TABLE FRAUD_ALERTS
(
    -- PK from Oracle sequence FD_SEQ (JPA @SequenceGenerator — no trigger needed)
    ALERT_ID            NUMBER(10)          NOT NULL,

    TXN_ID              CHAR(16)            NOT NULL,
    ACCT_NO             CHAR(10)            NOT NULL,

    -- NUMBER(15,2). Never use FLOAT.
    TXN_AMOUNT          NUMBER(15, 2)       NOT NULL,

    -- NUMBER(7,4) — score range 0.0000–1.0000
    FRAUD_SCORE         NUMBER(7, 4)        NOT NULL,

    -- Alert lifecycle state machine
    ALERT_STATUS        VARCHAR2(10)        DEFAULT 'PENDING'  NOT NULL,

    -- Assigned analyst (set when status moves to REVIEWED)
    ANALYST_ID          CHAR(8),

    -- Free-text resolution notes from analyst
    RESOLUTION_NOTES    VARCHAR2(255),

    -- Set to 'Y' once archived to cold storage (future batch process)
    ARCHIVED_FLAG       CHAR(1)             DEFAULT 'N'        NOT NULL,
    ARCHIVE_TS          TIMESTAMP,

    CREATED_TS          TIMESTAMP           DEFAULT CURRENT_TIMESTAMP NOT NULL,
    LAST_UPDATE_TS      TIMESTAMP           DEFAULT CURRENT_TIMESTAMP NOT NULL,

    -- ---- Constraints ----
    CONSTRAINT PK_FRAUD_ALERTS
        PRIMARY KEY (ALERT_ID),

    CONSTRAINT FK_ALERT_TXN
        FOREIGN KEY (TXN_ID)
        REFERENCES TXN_QUEUE (TXN_ID),

    CONSTRAINT CHK_ALERT_STATUS
        CHECK (ALERT_STATUS IN ('PENDING', 'REVIEWED', 'CLOSED', 'ESCALATED')),

    CONSTRAINT CHK_FRAUD_SCORE
        CHECK (FRAUD_SCORE BETWEEN 0 AND 1),

    CONSTRAINT CHK_ARCHIVED_FLAG
        CHECK (ARCHIVED_FLAG IN ('Y', 'N')),

    CONSTRAINT CHK_TXN_AMOUNT_ALERT
        CHECK (TXN_AMOUNT > 0)
);

-- ---- Indexes ----
-- Supports case management queries: open alerts per account
CREATE INDEX IX_ALERT_ACCT_STATUS
    ON FRAUD_ALERTS (ACCT_NO, ALERT_STATUS, CREATED_TS);

-- Supports analyst dashboard: alerts by status and creation time
CREATE INDEX IX_ALERT_STATUS_TS
    ON FRAUD_ALERTS (ALERT_STATUS, CREATED_TS);

-- ---- Column documentation ----
COMMENT ON TABLE FRAUD_ALERTS IS
    'Every transaction scoring >= 0.75. Written by AlertWriterService within @Transactional. Consumed by case management system via FRAUD.ALERT.QUEUE.';

COMMENT ON COLUMN FRAUD_ALERTS.ALERT_ID IS
    'Surrogate PK. Generated by JPA @SequenceGenerator (FD_SEQ).';
COMMENT ON COLUMN FRAUD_ALERTS.FRAUD_SCORE IS
    'Composite fraud score. NUMBER(7,4). Range 0.0000–1.0000.';
COMMENT ON COLUMN FRAUD_ALERTS.ALERT_STATUS IS
    'State machine: PENDING→REVIEWED→CLOSED or PENDING→ESCALATED (OFAC/PEP hits only).';
COMMENT ON COLUMN FRAUD_ALERTS.ANALYST_ID IS
    'Set by case management system when alert is assigned for review.';

PROMPT Table FRAUD_ALERTS created.
PROMPT Indexes IX_ALERT_ACCT_STATUS, IX_ALERT_STATUS_TS created.
COMMIT;
